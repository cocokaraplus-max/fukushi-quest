-- fq-zukan-69-v1 — 図鑑を 72体 → 69体 にする（2026-09-14）
--
-- 絵の向きを直したときに、同じ絵が2組あることと、
-- 元データで1枚に複数体入っているものがあることが分かったので整理した。
--
--   旧35 / 旧36（同じ絵）      → 旧36 だけ残す
--   旧49（箱パンダ3体）        → 3体まとめて1体
--   旧65（旧49の1体と同じ）    → 消す
--   旧19 / 旧64（同じ2匹組）   → 旧64 だけ残す
--   2体入っているもの          → 2体で1体（そのまま）
--
--   72 − 3 = 69体。番号は 1〜69 に詰め直してある。
--
-- ★ゴール報酬は 旧31（青いネコ）。番号が詰まって 30 になった。
--
-- 【どこに流すか】Supabase（FUKUSHI QUEST のプロジェクト）の SQL Editor
--   ※ TASUKARU の Supabase ではありません。別プロジェクトです。
-- 【いつ流すか】img/zukan/ の入れ替えと patch_fq_zukan_69.py のあと
-- 【消すもの】70番以上の所持記録だけ（本番前なので通常は0件）
-- ============================================================


-- 1. 体数とゴール報酬
update zukan_config set value = 69 where key = 'char_count';
update zukan_config set value = 30 where key = 'goal_char';


-- 2. もう存在しない番号の所持記録を消す
--    ★where true は要らない（条件が付いているので安全装置に弾かれない）
delete from zukan_owned where char_id > 69;


